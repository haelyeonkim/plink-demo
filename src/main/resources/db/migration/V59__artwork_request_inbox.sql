ALTER TABLE artwork_request ADD COLUMN first_requested_at TIMESTAMP;
ALTER TABLE artwork_request ADD COLUMN requested_at TIMESTAMP;
ALTER TABLE artwork_request ADD COLUMN interest_at TIMESTAMP;
ALTER TABLE artwork_request ADD COLUMN hold_requested_at TIMESTAMP;
ALTER TABLE artwork_request ADD COLUMN purchase_at TIMESTAMP;
ALTER TABLE artwork_request ADD COLUMN processing_state VARCHAR(20) NOT NULL DEFAULT 'UNREAD'
    CHECK (processing_state IN ('UNREAD', 'REVIEWED', 'CONTACTING', 'DONE'));
ALTER TABLE artwork_request ADD COLUMN assignee VARCHAR(200) NOT NULL DEFAULT '';
ALTER TABLE artwork_request ADD COLUMN internal_note VARCHAR(2000) NOT NULL DEFAULT '';
UPDATE artwork_request r SET owner_sub = (SELECT l.owner_sub FROM protected_link l WHERE l.id = r.link_id),
    holder_id = (SELECT p.holder_id FROM link_recipient p WHERE p.id = r.recipient_id),
    link_title = (SELECT l.title FROM protected_link l WHERE l.id = r.link_id),
    first_requested_at = COALESCE((SELECT MIN(e.occurred_at) FROM artwork_request_event e WHERE e.request_id=r.id AND e.actor_type='RECIPIENT'), r.updated_at),
    requested_at = COALESCE((SELECT MAX(e.occurred_at) FROM artwork_request_event e WHERE e.request_id=r.id AND e.actor_type='RECIPIENT'), r.updated_at),
    interest_at = (SELECT MAX(e.occurred_at) FROM artwork_request_event e WHERE e.request_id=r.id AND e.action='INTEREST'),
    hold_requested_at = (SELECT MAX(e.occurred_at) FROM artwork_request_event e WHERE e.request_id=r.id AND e.action='REQUEST_HOLD'),
    purchase_at = (SELECT MAX(e.occurred_at) FROM artwork_request_event e WHERE e.request_id=r.id AND e.action='PURCHASE');
-- Unknown historic senders stay visible only to account owners.
CREATE INDEX idx_request_inbox ON artwork_request(owner_sub, requested_at, id);
CREATE INDEX idx_request_holder ON artwork_request(holder_id);
CREATE TABLE artwork_request_work_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT NOT NULL REFERENCES artwork_request(id),
    actor VARCHAR(255) NOT NULL,
    before_state TEXT NOT NULL,
    after_state TEXT NOT NULL,
    occurred_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_request_work_history ON artwork_request_work_event(request_id, id);
