-- Talking to the room: a chat for people who have come in, and a board of booth and
-- organiser notices. Both belong to one event and are read from the holder's ticket.

-- One line in the event's chat. ticket_id is null for the organiser, who writes as
-- 운영팀. A reply quotes the message it answers by id; the quoted text is read from it,
-- so hiding the original hides the quote too.
CREATE TABLE chat_message (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id    BIGINT       NOT NULL REFERENCES event_session(id) ON DELETE CASCADE,
    ticket_id     BIGINT       REFERENCES ticket(id) ON DELETE SET NULL,
    staff         BOOLEAN      NOT NULL DEFAULT FALSE,
    notice        BOOLEAN      NOT NULL DEFAULT FALSE,
    body          VARCHAR(500) NOT NULL,
    reply_to      BIGINT       REFERENCES chat_message(id) ON DELETE SET NULL,
    like_count    INT          NOT NULL DEFAULT 0,
    report_count  INT          NOT NULL DEFAULT 0,
    hidden        BOOLEAN      NOT NULL DEFAULT FALSE,
    -- Set while the message is held at the top: a notice until taken down, a popular
    -- message for a while.
    pinned_until  TIMESTAMP,
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_chat_message_session ON chat_message(session_id, id);
CREATE INDEX idx_chat_message_ticket ON chat_message(ticket_id, created_at);

-- Who liked what, once each, so a like can be taken back.
CREATE TABLE chat_like (
    message_id BIGINT NOT NULL REFERENCES chat_message(id) ON DELETE CASCADE,
    ticket_id  BIGINT NOT NULL REFERENCES ticket(id) ON DELETE CASCADE,
    PRIMARY KEY (message_id, ticket_id)
);

-- Who reported what, once each.
CREATE TABLE chat_report (
    message_id BIGINT NOT NULL REFERENCES chat_message(id) ON DELETE CASCADE,
    ticket_id  BIGINT NOT NULL REFERENCES ticket(id) ON DELETE CASCADE,
    PRIMARY KEY (message_id, ticket_id)
);

-- A ticket the organiser has stopped from writing. It can still read.
CREATE TABLE chat_mute (
    session_id BIGINT    NOT NULL REFERENCES event_session(id) ON DELETE CASCADE,
    ticket_id  BIGINT    NOT NULL REFERENCES ticket(id) ON DELETE CASCADE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (session_id, ticket_id)
);

-- The chat's rules for one event. An event with no row uses the defaults.
CREATE TABLE chat_setting (
    session_id        BIGINT  PRIMARY KEY REFERENCES event_session(id) ON DELETE CASCADE,
    enabled           BOOLEAN NOT NULL DEFAULT TRUE,
    cooldown_seconds  INT     NOT NULL DEFAULT 60,
    max_length        INT     NOT NULL DEFAULT 200,
    hot_likes         INT     NOT NULL DEFAULT 20,
    hot_minutes       INT     NOT NULL DEFAULT 10,
    report_hide       INT     NOT NULL DEFAULT 3
);

-- One notice on the event's board, from a booth (written at its terminal) or from the
-- organiser. It shows between starts_at and ends_at; an organiser's can be pinned.
CREATE TABLE ad_post (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id  BIGINT        NOT NULL REFERENCES event_session(id) ON DELETE CASCADE,
    booth_id    BIGINT        REFERENCES booth(id) ON DELETE CASCADE,
    category    VARCHAR(16)   NOT NULL,
    title       VARCHAR(80)   NOT NULL,
    body        VARCHAR(1000) NOT NULL,
    place       VARCHAR(60),
    starts_at   TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ends_at     TIMESTAMP,
    pinned      BOOLEAN       NOT NULL DEFAULT FALSE,
    hidden      BOOLEAN       NOT NULL DEFAULT FALSE,
    view_count  INT           NOT NULL DEFAULT 0,
    created_at  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_ad_post_session ON ad_post(session_id, starts_at);
