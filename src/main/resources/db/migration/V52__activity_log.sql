-- Everything that happens, one row each, for statistics and for answering "what
-- happened" later. Append-only and kept without a time limit.
--
-- Rows are never joined back by foreign key: an event, ticket or gate that is deleted
-- keeps its history. The domain tables (admission_event, face_attempt, link_view,
-- chat_message ...) stay the source of truth for their features; this is the copy that
-- puts all of them, plus every request and error, on one time line.
--
-- Secrets never land here: personal tokens in paths are cut short, and passwords,
-- codes, tokens, passkey assertions and face images are dropped from request bodies.
CREATE TABLE activity_log (
    id           BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    category     VARCHAR(16)  NOT NULL,
    action       VARCHAR(64)  NOT NULL,
    ok           BOOLEAN      NOT NULL DEFAULT TRUE,
    result       VARCHAR(40),
    session_id   BIGINT,
    -- Who: ADMIN (an account), HOLDER (a ticket), GATE, BOOTH (a booth manager),
    -- RECIPIENT (someone opening an export), SYSTEM or ANON.
    actor_type   VARCHAR(12),
    actor_id     VARCHAR(80),
    actor_email  VARCHAR(320),
    ticket_id    BIGINT,
    gate_id      VARCHAR(32),
    booth_id     BIGINT,
    summary      VARCHAR(500),
    -- The rest of what is known, as a JSON object.
    detail       TEXT,
    http_method  VARCHAR(8),
    path         VARCHAR(500),
    status       INT,
    duration_ms  INT,
    ip           VARCHAR(64),
    user_agent   VARCHAR(500),
    request_id   VARCHAR(40)
);
CREATE INDEX idx_activity_time ON activity_log(occurred_at);
CREATE INDEX idx_activity_session ON activity_log(session_id, occurred_at);
CREATE INDEX idx_activity_category ON activity_log(category, occurred_at);
CREATE INDEX idx_activity_ticket ON activity_log(ticket_id);

-- A filter on the log screen someone wanted to come back to.
CREATE TABLE data_view (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(60)  NOT NULL,
    filters     TEXT         NOT NULL,
    created_by  VARCHAR(320),
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Data handed to an organiser: the files are made once, when asked for, and served
-- from a link that opens for a while and a number of downloads. Only the HMAC of the
-- link's token is kept, like every other link here.
CREATE TABLE data_export (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id      BIGINT,
    session_title   VARCHAR(200),
    recipient_name  VARCHAR(120) NOT NULL,
    recipient_email VARCHAR(320) NOT NULL,
    spec            TEXT         NOT NULL,
    pii             VARCHAR(12)  NOT NULL,
    note            VARCHAR(1000),
    token_hmac      VARCHAR(64)  NOT NULL UNIQUE,
    -- Sealed, so the console can show and mail the link again while it is open.
    token_cipher    TEXT,
    expires_at      TIMESTAMP    NOT NULL,
    max_downloads   INT,
    downloads       INT          NOT NULL DEFAULT 0,
    require_code    BOOLEAN      NOT NULL DEFAULT TRUE,
    created_by      VARCHAR(320),
    created_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    closed_at       TIMESTAMP,
    purged_at       TIMESTAMP
);

CREATE TABLE data_export_file (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    export_id   BIGINT       NOT NULL REFERENCES data_export(id) ON DELETE CASCADE,
    name        VARCHAR(120) NOT NULL,
    label       VARCHAR(120),
    description VARCHAR(300),
    rows_count  INT          NOT NULL DEFAULT 0,
    content     TEXT
);
CREATE INDEX idx_export_file ON data_export_file(export_id);

-- Every open, code and download of an export link: who looked at the data, and when.
CREATE TABLE data_export_access (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    export_id   BIGINT       NOT NULL REFERENCES data_export(id) ON DELETE CASCADE,
    occurred_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    action      VARCHAR(16)  NOT NULL,
    file        VARCHAR(120),
    ip          VARCHAR(64),
    user_agent  VARCHAR(500)
);
CREATE INDEX idx_export_access ON data_export_access(export_id, occurred_at);
