-- An event over several days: the days it runs, and which of them each ticket admits.
--
-- event_day lists the days, in the venue's calendar (the turn of the day follows the
-- event's day_close_hour). A day may be closed - a rest day in the middle - and may
-- have its own hours; the last open day's close is when the event ends. An event with
-- no days keeps working as before: every ticket, every day, no end.
CREATE TABLE event_day (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id  BIGINT       NOT NULL REFERENCES event_session(id) ON DELETE CASCADE,
    day_date    DATE         NOT NULL,
    label       VARCHAR(20)  NOT NULL,
    opens_at    VARCHAR(5),
    closes_at   VARCHAR(5),
    closed      BOOLEAN      NOT NULL DEFAULT FALSE,
    UNIQUE (session_id, day_date)
);

-- A kind of ticket by the days it admits: a weekend pass, a Saturday pass. NULL days
-- means every day of the event. A ticket with no pass is an every-day ticket too.
CREATE TABLE ticket_pass (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id  BIGINT       NOT NULL REFERENCES event_session(id) ON DELETE CASCADE,
    name        VARCHAR(30)  NOT NULL,
    days        VARCHAR(400),
    position    INT          NOT NULL DEFAULT 0
);
CREATE INDEX idx_ticket_pass_session ON ticket_pass(session_id, position);

-- A pass with tickets on it cannot be removed; the console refuses before the database does.
ALTER TABLE ticket ADD COLUMN pass_id BIGINT REFERENCES ticket_pass(id);
CREATE INDEX idx_ticket_pass ON ticket(pass_id);
