-- Deliberately retain recipient/link identifiers and snapshots after an invitation is deleted.
CREATE TABLE artwork_request (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    artwork_id BIGINT NOT NULL REFERENCES artwork(id),
    recipient_id BIGINT NOT NULL,
    link_id BIGINT NOT NULL,
    recipient_email VARCHAR(320) NOT NULL,
    artwork_title VARCHAR(500) NOT NULL,
    interested BOOLEAN NOT NULL DEFAULT FALSE,
    hold_state VARCHAR(20) NOT NULL DEFAULT 'NONE',
    hold_until TIMESTAMP,
    purchase_intent BOOLEAN NOT NULL DEFAULT FALSE,
    purchased BOOLEAN NOT NULL DEFAULT FALSE,
    cancellation_requested BOOLEAN NOT NULL DEFAULT FALSE,
    version BIGINT NOT NULL DEFAULT 0,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (artwork_id, recipient_id),
    CHECK (hold_state IN ('NONE', 'PENDING', 'HELD', 'REJECTED', 'CANCELLED', 'EXPIRED', 'CLOSED'))
);
-- A database constraint, in addition to the artwork row lock, prevents duplicate holds.
CREATE TABLE artwork_reservation (
    artwork_id BIGINT PRIMARY KEY REFERENCES artwork(id),
    request_id BIGINT NOT NULL UNIQUE REFERENCES artwork_request(id)
);
CREATE INDEX idx_artwork_request_updated ON artwork_request(updated_at);
CREATE INDEX idx_artwork_request_recipient ON artwork_request(recipient_id);
CREATE TABLE artwork_request_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT REFERENCES artwork_request(id),
    artwork_id BIGINT NOT NULL,
    actor_type VARCHAR(20) NOT NULL,
    actor_id VARCHAR(255) NOT NULL,
    action VARCHAR(40) NOT NULL,
    before_state TEXT NOT NULL,
    after_state TEXT NOT NULL,
    reason VARCHAR(1000) NOT NULL,
    command_key VARCHAR(80),
    command_body TEXT,
    occurred_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (request_id, command_key)
);
CREATE INDEX idx_artwork_request_event_request ON artwork_request_event(request_id, id);
