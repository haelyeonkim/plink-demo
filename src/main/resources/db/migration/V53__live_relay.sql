-- Live messages too large for a Postgres NOTIFY.
--
-- Copies of the app running side by side tell each other about a scan or a chat line
-- with NOTIFY, whose payload stops at 8000 bytes. The console's occupancy snapshot
-- carries the latest movements and goes past that on a busy door, so a large message
-- is written here and only its id is sent. Rows are read within moments of being
-- written and are deleted a few minutes later; nothing else reads this table.
CREATE TABLE live_relay (
    id          BIGINT     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    body        TEXT       NOT NULL,
    created_at  TIMESTAMP  NOT NULL DEFAULT CURRENT_TIMESTAMP
);
