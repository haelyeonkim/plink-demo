-- Booth managers: the people the organiser trusts to run one booth from their own phone.
--
-- A manager is invited by email and proves it the way a ticket holder does - a code to
-- that mailbox, then a passkey - so the holder row is the person, shared with any
-- tickets they hold. Only a keyed hash of the invite link's token is kept: reading the
-- table does not hand out a way into a booth.
--
-- A revoked manager keeps the row, so the console can still say who used to run the
-- booth and when; it is the status, checked on every request, that shuts them out.
CREATE TABLE booth_manager (
    id           BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id   BIGINT       NOT NULL REFERENCES event_session(id) ON DELETE CASCADE,
    booth_id     BIGINT       NOT NULL REFERENCES booth(id) ON DELETE CASCADE,
    email        VARCHAR(320) NOT NULL,
    token_hash   VARCHAR(128) NOT NULL,
    holder_id    BIGINT       REFERENCES holder(id) ON DELETE SET NULL,
    -- INVITED until the passkey is bound, then ACTIVE; REVOKED is the organiser's word.
    status       VARCHAR(16)  NOT NULL DEFAULT 'INVITED',
    invited_at   TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    claimed_at   TIMESTAMP,
    last_seen_at TIMESTAMP
);
CREATE UNIQUE INDEX uq_booth_manager_token ON booth_manager(token_hash);
-- One invitation per address per booth: two would be two links into the same seat.
CREATE UNIQUE INDEX uq_booth_manager_email ON booth_manager(booth_id, email);
CREATE INDEX idx_booth_manager_booth ON booth_manager(booth_id);
