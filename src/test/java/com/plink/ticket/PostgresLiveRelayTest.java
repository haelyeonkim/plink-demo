package com.plink.ticket;

import com.plink.ticket.live.PostgresLiveRelay;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.condition.EnabledIfEnvironmentVariable;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import java.util.concurrent.BlockingQueue;
import java.util.concurrent.LinkedBlockingQueue;
import java.util.concurrent.TimeUnit;

import static org.junit.jupiter.api.Assertions.*;

/**
 * The relay against a real Postgres, which H2 cannot stand in for: LISTEN/NOTIFY and its
 * 8000-byte payload limit are the point. Runs only when given a database to use, e.g.
 * {@code PLINK_RELAY_TEST_URL=jdbc:postgresql://127.0.0.1:54330/passlink PLINK_RELAY_TEST_USER=...
 * PLINK_RELAY_TEST_PASSWORD=... ./mvnw test -Dtest=PostgresLiveRelayTest}. It works in a
 * schema of its own and drops it afterwards.
 */
@EnabledIfEnvironmentVariable(named = "PLINK_RELAY_TEST_URL", matches = ".+")
class PostgresLiveRelayTest {

    private final String base = System.getenv("PLINK_RELAY_TEST_URL");
    private final String user = System.getenv().getOrDefault("PLINK_RELAY_TEST_USER", "");
    private final String password = System.getenv().getOrDefault("PLINK_RELAY_TEST_PASSWORD", "");
    private final String schema = "relay_test_" + Long.toHexString(System.nanoTime());
    private JdbcTemplate admin;
    private PostgresLiveRelay sender;
    private PostgresLiveRelay receiver;
    private PostgresLiveRelay otherSchema;

    private JdbcTemplate jdbc(String url) {
        return new JdbcTemplate(new DriverManagerDataSource(url, user, password));
    }

    @BeforeEach
    void setUp() {
        admin = jdbc(base);
        admin.execute("CREATE SCHEMA " + schema);
        admin.execute("CREATE TABLE " + schema + ".live_relay (id BIGINT GENERATED BY DEFAULT AS IDENTITY "
            + "PRIMARY KEY, body TEXT NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP)");
        String url = base + (base.contains("?") ? "&" : "?") + "currentSchema=" + schema;
        sender = new PostgresLiveRelay(jdbc(url), url, user, password, schema);
        receiver = new PostgresLiveRelay(jdbc(url), url, user, password, schema);
        otherSchema = new PostgresLiveRelay(jdbc(url), url, user, password, schema + "_other");
    }

    @AfterEach
    void tearDown() {
        for (PostgresLiveRelay relay : new PostgresLiveRelay[] { sender, receiver, otherSchema }) {
            if (relay != null) relay.destroy();
        }
        admin.execute("DROP SCHEMA IF EXISTS " + schema + " CASCADE");
    }

    @Test
    void smallAndLargeMessagesBothArriveOnlyInTheirOwnSchema() throws Exception {
        BlockingQueue<String> heard = new LinkedBlockingQueue<>();
        BlockingQueue<String> heardElsewhere = new LinkedBlockingQueue<>();
        receiver.start(heard::add);
        otherSchema.start(heardElsewhere::add);
        Thread.sleep(1500); // let both LISTENs register

        sender.send("{\"small\":true}");
        String large = "{\"big\":\"" + "x".repeat(20_000) + "\"}";
        sender.send(large);

        assertEquals("{\"small\":true}", heard.poll(5, TimeUnit.SECONDS));
        assertEquals(large, heard.poll(5, TimeUnit.SECONDS));
        assertNull(heardElsewhere.poll(1, TimeUnit.SECONDS));
    }
}
