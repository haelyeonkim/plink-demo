-- What a holder's ticket shows about the venue: maps, places such as toilets, written
-- guidance such as parking, the timetable, and links out.
--
-- The organiser builds it from sections of a few kinds rather than one screen per topic,
-- so a smoking area or a nursing room is one more list of places, not a feature. Each
-- section keeps its own shape as JSON in content; the service checks that shape on the
-- way in, so what is stored is only what the kind allows.
CREATE TABLE venue_section (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id  BIGINT       NOT NULL REFERENCES event_session(id) ON DELETE CASCADE,
    kind        VARCHAR(16)  NOT NULL,
    title       VARCHAR(40)  NOT NULL,
    position    INT          NOT NULL DEFAULT 0,
    visible     BOOLEAN      NOT NULL DEFAULT FALSE,
    content     TEXT         NOT NULL,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_venue_section_session ON venue_section(session_id, position);

-- A floor plan uploaded for a map section. The bytes live in the same private store as
-- the board's photos; an image no map names a day after upload is removed.
CREATE TABLE venue_image (
    id              VARCHAR(36)  PRIMARY KEY,
    session_id      BIGINT       NOT NULL REFERENCES event_session(id) ON DELETE CASCADE,
    storage_key     VARCHAR(255) NOT NULL,
    storage_backend VARCHAR(20)  NOT NULL,
    media_type      VARCHAR(50)  NOT NULL,
    byte_size       BIGINT       NOT NULL,
    created_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_venue_image_session ON venue_image(session_id);
